


# Fourier-integral evaluation of the standard symmetric stable pdf for
# 0.5 <= alpha <= 2 and |x| below the tail-series threshold, using
# precomputed quadrature nodes/weights from qastable (Ament & O'Neil).
function stable_sym_pdf_fourier_integral(x::Float64, a::Float64)
    gx = GX_SYM_PDF
    gw = GW_SYM_PDF

    rank_scaling = (-log(eps(Float64)))^(1 / a)

    pdf = 0.0
    @inbounds @simd for j in eachindex(gx, gw)
        gxj = rank_scaling * gx[j]
        pdf += gw[j] * cos(x * gxj) * exp(-gxj^a)
    end
    return rank_scaling / pi * pdf
end

