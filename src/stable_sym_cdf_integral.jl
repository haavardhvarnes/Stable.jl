

# Fourier-integral evaluation of the standard symmetric stable cdf, using
# precomputed quadrature nodes/weights from qastable (Ament & O'Neil).
function stable_sym_cdf_integral(x::Float64, a::Float64)
    gx = GX_SYM_CDF
    gw = GW_SYM_CDF

    rank_scaling = (-log(eps(Float64)))^(1 / a)

    cdf = 0.5
    @inbounds @simd for j in eachindex(gx, gw)
        gxj = rank_scaling * gx[j]
        cdf += rank_scaling / pi * gw[j] * sin(x * gxj) * exp(-gxj^a) / gxj
    end
    return cdf
end

