


# Fourier-integral evaluation of the standard asymmetric stable cdf, using
# precomputed quadrature nodes/weights from qastable (Ament & O'Neil).
function stable_cdf_integral(x::Float64, a::Float64, b::Float64)
    a >= 1.1 || throw(DomainError(a,
        "asymmetric (β ≠ 0) stable cdf requires α ∈ [1.1, 2]"))
    gx = GX_CDF
    gw = GW_CDF

    rank_scaling = (-log(eps(Float64)))^(1 / a)
    z = -b * tan(a * pi / 2)

    cdf = 0.5
    @inbounds @simd for j in eachindex(gx, gw)
        gxj = rank_scaling * gx[j]
        gxj_to_a = gxj^a
        h = (x - z) * gxj + z * gxj_to_a
        cdf += rank_scaling / pi * gw[j] * sin(h) * exp(-gxj_to_a) / gxj
    end
    return cdf
end

